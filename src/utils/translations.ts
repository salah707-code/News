export function getTranslation(lang: Language, key: keyof typeof TRANSLATIONS['ar'], params?: Record<string, string | number>): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.ar;
  let text = (dict as any)[key] || TRANSLATIONS.ar[key] || String(key);
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}
